#!/usr/bin/env python3
"""Generate the OpenCode adapter layer from the canonical Claude Code layer.

The repository is dual-harness:

  .claude/    canonical source, used directly by Claude Code
  .opencode/  generated adapter, used by OpenCode

Run this after editing anything under .claude/agents or .claude/skills:

    python3 tools/sync-opencode.py

Use --check in CI to fail when the committed adapter is stale:

    python3 tools/sync-opencode.py --check
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CANON_AGENTS = ROOT / ".claude" / "agents"
CANON_SKILLS = ROOT / ".claude" / "skills"
OUT_AGENTS = ROOT / ".opencode" / "agents"
OUT_SKILLS = ROOT / ".opencode" / "skills"
OUT_COMMANDS = ROOT / ".opencode" / "commands"
OUT_DOCS = ROOT / ".opencode" / "docs"

GENERATED = "Generated by tools/sync-opencode.py from {}; do not edit directly."

AGENT_TOOL_ACTIONS = {
    "Read": "read",
    "Glob": "glob",
    "Grep": "grep",
    "Write": "edit",
    "Edit": "edit",
    "Bash": "shell",
    "WebSearch": "websearch",
    "WebFetch": "webfetch",
    "Agent": "subagent",
    "Task": "subagent",
    "AskUserQuestion": "question",
}

# These skills inspect or edit canonical Claude sources. Keep their .claude/
# paths intact so they continue to validate the source of truth.
KEEP_CLAUDE_PATHS = {"skill-test", "skill-improve"}

# setup-engine edits CLAUDE.md directly; in the dual-harness repo it must also
# mirror the change into AGENTS.md.
KEEP_CLAUDE_MD = {"setup-engine"}

SPECIAL_NOTES = {
    "skill-test": (
        "> **Dual-harness note.** This skill validates the canonical sources in "
        "`.claude/`. The OpenCode adapter is generated from them. Run "
        "`python3 tools/sync-opencode.py` after changing a canonical skill or agent, "
        "and `python3 tools/validate-opencode.py` to check the generated layer."
    ),
    "skill-improve": (
        "> **Dual-harness note.** Improve the canonical skill or agent in `.claude/`, "
        "then run `python3 tools/sync-opencode.py` so `.opencode/` stays in sync."
    ),
    "setup-engine": (
        "> **Dual-harness note.** This skill writes `CLAUDE.md` for Claude Code. "
        "`AGENTS.md` reads the engine and language from `project.yaml`, so no "
        "Technology Stack mirror is required; keep any non-engine guidance in the "
        "two entry files aligned if you change it."
    ),
}


def fail(message: str) -> None:
    print(f"sync-opencode: {message}", file=sys.stderr)
    raise SystemExit(1)


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Return (top-level frontmatter fields, body).

    The studio frontmatter is deliberately simple: one `key: value` pair per
    line. Values that contain colons (descriptions) are kept whole.
    """
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 4)
    if end == -1:
        return {}, text
    raw = text[4:end]
    body = text[end + 5 :]
    fields: dict[str, str] = {}
    for line in raw.splitlines():
        if not line or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        fields[key.strip()] = value.strip()
    return fields, body


def parse_list(value: str) -> list[str]:
    value = value.strip()
    if value.startswith("[") and value.endswith("]"):
        value = value[1:-1]
    return [part.strip().strip("\"'") for part in value.split(",") if part.strip()]


def parse_tools(value: str) -> set[str]:
    tools: set[str] = set()
    for part in value.split(","):
        name = part.strip()
        if not name:
            continue
        # Bash(...) grants the Bash tool; keep just the tool name.
        if "(" in name:
            name = name.split("(", 1)[0].strip()
        tools.add(name)
    return tools


def transform_shell(command: str) -> str:
    command = command.replace('${CLAUDE_SKILL_DIR}/../../hooks/', '.claude/hooks/')
    command = command.replace('${CLAUDE_SKILL_DIR}/../../scripts/', '.claude/scripts/')
    command = command.replace('${CLAUDE_SKILL_DIR}/../../skills/', '.opencode/skills/')
    command = command.replace("${CLAUDE_SKILL_DIR}", ".opencode/skills")
    command = command.replace('"${CLAUDE_SKILL_DIR}/../../', '".claude/')
    return command


def transform_body(text: str, skill_id: str | None = None) -> str:
    """Rewrite Claude-specific vocabulary and paths for OpenCode."""

    # Harness-specific docs get OpenCode variants.
    text = text.replace(".claude/docs/model-tiers.md", ".opencode/docs/model-selection.md")
    text = text.replace(".claude/docs/hooks-reference.md", ".opencode/docs/hooks-reference.md")
    text = text.replace(".claude/docs/setup-requirements.md", ".opencode/docs/opencode-setup.md")
    text = text.replace(".claude/docs/settings-local-template.md", ".opencode/docs/opencode-setup.md")
    text = text.replace(".claude/docs/rules-reference.md", ".opencode/docs/rules-reference.md")
    text = text.replace(".claude/docs/quick-start.md", ".opencode/docs/opencode-setup.md")
    text = text.replace(".claude/docs/coordination-rules.md", ".opencode/docs/coordination-rules.md")
    text = text.replace(".claude/docs/context-management.md", ".opencode/docs/context-management.md")
    text = text.replace(".claude/docs/agent-teams.md", ".opencode/docs/agent-teams.md")
    text = text.replace(".claude/docs/coding-standards.md", ".opencode/docs/coding-standards.md")
    text = text.replace(".claude/docs/directory-structure.md", ".opencode/docs/directory-structure.md")
    text = text.replace(".claude/docs/skills-reference.md", ".opencode/docs/skills-reference.md")
    text = text.replace(".claude/docs/agent-roster.md", ".opencode/docs/agents-reference.md")

    text = text.replace(".claude/settings.json", "opencode.jsonc")
    text = text.replace(".claude/statusline.sh", "OpenCode's built-in status display")

    if skill_id not in KEEP_CLAUDE_PATHS:
        text = text.replace(".claude/skills/", ".opencode/skills/")
        text = text.replace(".claude/agents/", ".opencode/agents/")

    if skill_id not in KEEP_CLAUDE_MD:
        text = text.replace("CLAUDE.md", "AGENTS.md")

    # Shell prelude paths.
    text = transform_shell(text)

    # AskUserQuestion -> OpenCode's question tool.
    text = text.replace("AskUserQuestion is not in your `tools:` grant", "The `question` tool is not in your tool grant")
    text = text.replace("AskUserQuestion is not in your tools grant", "The `question` tool is not in your tool grant")
    text = text.replace("Every `AskUserQuestion` call", "Every `question` tool call")
    text = text.replace("Use `AskUserQuestion`", "Use the `question` tool")
    text = text.replace("use `AskUserQuestion`", "use the `question` tool")
    text = text.replace("via `AskUserQuestion`", "with the `question` tool")
    text = text.replace("`AskUserQuestion` call", "`question` tool call")
    text = text.replace("`AskUserQuestion` decision point", "`question` tool decision point")
    text = text.replace("`AskUserQuestion`", "`question` tool")
    text = text.replace("AskUserQuestion", "question tool")
    text = text.replace("the `question` tool tool", "the `question` tool")
    text = text.replace("question tool tool", "question tool")

    # Agent tool -> OpenCode's subagent tool.
    text = text.replace("`Agent` tool", "`subagent` tool")
    text = text.replace("`Agent` calls", "`subagent` calls")
    text = text.replace("`Agent` call", "`subagent` call")
    text = text.replace("via `Agent`", "with the `subagent` tool")
    text = text.replace("`Agent`", "`subagent`")
    text = text.replace("Agent delegation", "Subagent delegation")
    text = text.replace("Agent tool", "subagent tool")
    text = text.replace("Agent calls", "subagent calls")

    # Claude-specific words left in prose.
    text = text.replace("Anthropic's Agent Skills", "Agent Skills")
    text = text.replace("Claude Code", "OpenCode")
    text = text.replace("Claude-evaluated", "model-evaluated")
    text = text.replace("Claude", "the model")
    text = text.replace("the model Code", "OpenCode")
    text = text.replace("the model session", "model session")
    text = text.replace("Opus-tier", "high-effort tier")
    text = text.replace("Sonnet-tier", "standard-effort tier")
    text = text.replace("Haiku-tier", "lightweight tier")

    # Claude-only environment variables that should not appear in OpenCode skill
    # instructions.
    text = text.replace("CLAUDE_PROJECT_DIR", "the project root")
    text = text.replace("CLAUDE_SKILL_DIR", ".opencode/skills")
    text = text.replace("CLAUDE.local.md", "a local AGENTS.md override")
    text = text.replace("CLAUDE_CODE_EXPERIMENTAL_AGENT_TEAMS", "OpenCode's subagent depth setting")
    text = text.replace("CLAUDE_CODE_SUBAGENT_MODEL_FORCE", "the agent's model setting")
    text = text.replace("CLAUDE_CODE_SUBAGENT_MODEL", "the agent's model setting")
    text = text.replace("CLAUDE_CODE_GIT_BASH_PATH", "the shell configuration")

    return text


def extract_shell_prelude(body: str) -> tuple[list[str], str]:
    """Pull !`cmd` lines out of a skill body.

    Claude Code evaluates these lines when a skill is invoked. OpenCode evaluates
    shell blocks only in commands, so the generated command carries them. The
    generated skill keeps a readable instruction in their place.
    """
    commands: list[str] = []
    out: list[str] = []
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith("!`") and stripped.endswith("`") and len(stripped) > 3:
            command = transform_shell(stripped[2:-1])
            commands.append(command)
            out.append(
                "If the calling command did not already resolve this, run it now "
                f"and use its output as-is: `{command}`"
            )
        else:
            out.append(line)
    return commands, "\n".join(out)


def agent_permissions(tools: set[str]) -> list[tuple[str, str, str]]:
    """Translate Claude tool grants into OpenCode permission rules.

    We deny the tools the agent did NOT have instead of denying everything and
    re-allowing. That preserves the global shell safety rules for agents that
    legitimately have Bash; a broad `shell: allow` would override every global
    deny rule because agent rules are appended last.
    """
    actions = {AGENT_TOOL_ACTIONS[t] for t in tools if t in AGENT_TOOL_ACTIONS}
    rules: list[tuple[str, str, str]] = []

    if "edit" not in actions:
        rules.append(("edit", "*", "deny"))
    if "shell" not in actions:
        rules.append(("shell", "*", "deny"))
    if "websearch" not in actions:
        rules.append(("websearch", "*", "deny"))
    if "webfetch" not in actions:
        rules.append(("webfetch", "*", "deny"))
    if "subagent" not in actions:
        rules.append(("subagent", "*", "deny"))

    # Subagents present choices to their caller rather than opening the question
    # tool themselves. Code Mode is denied to keep the tool surface small and
    # prevent a second path around file permissions.
    rules.append(("question", "*", "deny"))
    rules.append(("execute", "*", "deny"))

    return rules


def render_agent(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    fields, body = split_frontmatter(text)
    if "description" not in fields:
        fail(f"{path}: missing description")
    tools = parse_tools(fields.get("tools", ""))
    steps = fields.get("maxTurns", "20").strip() or "20"
    body = transform_body(body)

    preamble: list[str] = []
    skills = parse_list(fields.get("skills", ""))
    if skills:
        names = ", ".join(f"`{s}`" for s in skills)
        preamble.append(
            "## Skills to Load First\n\n"
            f"Before doing any work, load {names} with the `skill` tool and follow it."
        )
    if fields.get("memory", "").strip() == "project":
        preamble.append(
            "## Project Memory\n\n"
            f"Before starting, read `.claude/agent-memory/{path.stem}.md` if it exists. "
            "After finishing, append durable, reusable lessons to it. Never record "
            "temporary project state (an empty template, an engine not chosen yet, no "
            "tests yet); memory is gitignored and is not a project artifact."
        )
    if fields.get("isolation", "").strip() == "worktree":
        preamble.append(
            "## Isolation\n\n"
            "OpenCode does not automatically place subagents in a worktree. Do not modify "
            "`src/`; build throwaway work under `prototypes/` and use "
            "`git worktree add` if you need a separate checkout."
        )

    if preamble:
        body = "\n\n".join(preamble) + "\n\n" + body.lstrip()

    lines = [
        "---",
        f"description: {fields['description']}",
        "mode: subagent",
        f"steps: {steps}",
    ]
    rules = agent_permissions(tools)
    if rules:
        lines.append("permissions:")
        for action, resource, effect in rules:
            lines.append(f"  - action: {action}")
            lines.append(f'    resource: "{resource}"')
            lines.append(f"    effect: {effect}")
    lines.append("---")
    lines.append("")
    lines.append(f"<!-- {GENERATED.format(path.relative_to(ROOT))} -->")
    lines.append("")
    lines.append(body.rstrip())
    lines.append("")
    return "\n".join(lines)


def studio_agent() -> str:
    body = """# Studio Orchestrator

You are the OpenCode Game Studios orchestrator. You coordinate the studio's 49
specialist subagents and 74 workflows.

- Follow `AGENTS.md` and the instruction files loaded by `opencode.jsonc`.
- Use the `question` tool for structured decisions. If it is unavailable, list
  numbered options and end your turn.
- Delegate with the `subagent` tool. Use the most specific specialist, and keep
  the director -> lead -> specialist chain when a decision needs sign-off.
- Prefer a slash command (`/start`, `/gate-check`, `/dev-story`, ...) when one
  matches the task. Commands load the canonical workflow skill for you.
- Do not write files without the approval the collaboration protocol requires.
- Do not add model pins. Every agent inherits the session model.
"""
    return "\n".join(
        [
            "---",
            'description: "OpenCode Game Studios orchestrator. Coordinates the 49 specialist subagents and 74 workflows."',
            "mode: primary",
            "steps: 60",
            "---",
            "",
            f"<!-- {GENERATED.format('.opencode/agents/studio.md (hand-written in tools/sync-opencode.py)')} -->",
            "",
            body.rstrip(),
            "",
        ]
    )


def render_skill(skill_dir: Path) -> tuple[str, list[str]]:
    skill_id = skill_dir.name
    text = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
    fields, body = split_frontmatter(text)
    if "description" not in fields:
        fail(f"{skill_dir}/SKILL.md: missing description")

    shell_commands, body = extract_shell_prelude(body)
    body = transform_body(body, skill_id=skill_id)

    note = SPECIAL_NOTES.get(skill_id)
    if note:
        body = note + "\n\n" + body.lstrip()

    lines = [
        "---",
        f"name: {fields.get('name', skill_id)}",
        f"description: {fields['description']}",
    ]
    if fields.get("disable-model-invocation", "").lower() == "true":
        lines.extend(["metadata:", "  opencode/autoinvoke: false"])
    lines.append("---")
    lines.append("")
    lines.append(f"<!-- {GENERATED.format((skill_dir / 'SKILL.md').relative_to(ROOT))} -->")
    lines.append("")
    lines.append(body.rstrip())
    lines.append("")
    return "\n".join(lines), shell_commands


def render_command(skill_dir: Path, shell_commands: list[str]) -> str:
    skill_id = skill_dir.name
    text = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
    fields, _ = split_frontmatter(text)
    description = fields["description"]
    hint = fields.get("argument-hint", "").strip().strip('"')

    lines = [
        "---",
        f"description: {description}",
        "---",
        "",
        f"<!-- {GENERATED.format((skill_dir / 'SKILL.md').relative_to(ROOT))} -->",
        "",
        f"Load the `{skill_id}` skill with the skill tool, then follow it exactly.",
        "",
    ]
    if hint and hint not in {"[no arguments]", "[no argument]"}:
        lines.extend([f"Argument hint: {hint}", ""])
    if shell_commands:
        lines.extend(
            [
                "The following project configuration is resolved before the skill runs:",
                "",
            ]
        )
        for command in shell_commands:
            lines.append(f"!`{command}`")
        lines.append("")
    lines.extend(["User-supplied arguments:", "", "$ARGUMENTS", ""])
    return "\n".join(lines)


def build() -> dict[Path, str | bytes]:
    """Return every generated file as {path: content}."""
    files: dict[Path, str | bytes] = {}

    if not CANON_AGENTS.is_dir():
        fail(f"missing {CANON_AGENTS}")
    if not CANON_SKILLS.is_dir():
        fail(f"missing {CANON_SKILLS}")

    for agent in sorted(CANON_AGENTS.glob("*.md")):
        files[OUT_AGENTS / agent.name] = render_agent(agent)
    files[OUT_AGENTS / "studio.md"] = studio_agent()

    for skill_dir in sorted(p for p in CANON_SKILLS.iterdir() if p.is_dir()):
        if not (skill_dir / "SKILL.md").is_file():
            continue
        skill_text, shell_commands = render_skill(skill_dir)
        files[OUT_SKILLS / skill_dir.name / "SKILL.md"] = skill_text
        files[OUT_COMMANDS / f"{skill_dir.name}.md"] = render_command(skill_dir, shell_commands)

    # Supporting files (references, CONTRACT.md) are copied with the same text
    # transformations. They are collected separately because render_skill only
    # handles SKILL.md.
    for skill_dir in sorted(p for p in CANON_SKILLS.iterdir() if p.is_dir()):
        if not (skill_dir / "SKILL.md").is_file():
            continue
        for source in sorted(skill_dir.rglob("*")):
            if source.is_dir() or source.name == "SKILL.md":
                continue
            rel = source.relative_to(skill_dir)
            dest = OUT_SKILLS / skill_dir.name / rel
            if source.suffix == ".md":
                files[dest] = transform_body(
                    source.read_text(encoding="utf-8"), skill_id=skill_dir.name
                )
            else:
                # Binary support files are rare, but preserve them byte-for-byte.
                files[dest] = source.read_bytes()

    files[OUT_DOCS / "agents-reference.md"] = render_agents_reference()
    files[OUT_DOCS / "skills-reference.md"] = render_skills_reference()
    return files


def render_agents_reference() -> str:
    rows = []
    for agent in sorted(CANON_AGENTS.glob("*.md")):
        fields, _ = split_frontmatter(agent.read_text(encoding="utf-8"))
        tools = parse_tools(fields.get("tools", ""))
        posture = ", ".join(sorted(tools)) or "none"
        rows.append(
            f"| `{agent.stem}` | subagent | {fields.get('maxTurns', '20')} | {posture} |"
        )
    rows.append("| `studio` | primary | 60 | all built-in tools |")
    return "\n".join(
        [
            "# OpenCode Agents",
            "",
            f"<!-- {GENERATED.format('.claude/agents/*.md')} -->",
            "",
            "All specialist agents are subagents. The `studio` agent is the default",
            "primary agent. No agent pins a model; each inherits the session model.",
            "",
            "| Agent | Mode | Steps | Claude-side tool posture |",
            "|---|---|---:|---|",
            *rows,
            "",
            "The generated `.opencode/agents/*.md` files carry the OpenCode",
            "permissions that enforce this posture. See `permissions.md`.",
            "",
        ]
    )


def render_skills_reference() -> str:
    rows = []
    for skill_dir in sorted(p for p in CANON_SKILLS.iterdir() if p.is_dir()):
        skill = skill_dir / "SKILL.md"
        if not skill.is_file():
            continue
        fields, _ = split_frontmatter(skill.read_text(encoding="utf-8"))
        hint = fields.get("argument-hint", "").strip().strip('"').replace("|", "\\|")
        tools = fields.get("allowed-tools", "")
        # Keep the table readable; the generated commands/skills are authoritative.
        posture = "read/write" if re.search(r"\b(Write|Edit)\b", tools) else "read-only"
        auto = "no" if fields.get("disable-model-invocation", "").lower() == "true" else "yes"
        rows.append(
            f"| `/{skill_dir.name}` | `{skill_dir.name}` | {hint or '—'} | {posture} | {auto} |"
        )
    return "\n".join(
        [
            "# OpenCode Commands and Skills",
            "",
            f"<!-- {GENERATED.format('.claude/skills/*/SKILL.md')} -->",
            "",
            "Every skill has a matching slash command. The command loads the skill and",
            "passes `$ARGUMENTS` to it. `auto` says whether the model may discover the",
            "skill without the command (OpenCode `opencode/autoinvoke`).",
            "",
            "| Command | Skill ID | Arguments | Intended posture | Auto |",
            "|---|---|---|---|---|",
            *rows,
            "",
            "The intended posture is advisory in OpenCode: permissions are enforced per",
            "agent, not per skill. The safety plugin still blocks the critical write and",
            "read cases. Run read-only workflows under a read-only agent if you need hard",
            "enforcement.",
            "",
        ]
    )


def write_files(files: dict[Path, str | bytes]) -> None:
    # Generated directories are replaced wholesale. Hand-written OpenCode files
    # (plugins, docs, config) live outside these three directories.
    for directory in (OUT_AGENTS, OUT_SKILLS, OUT_COMMANDS):
        if directory.exists():
            shutil.rmtree(directory)
    OUT_DOCS.mkdir(parents=True, exist_ok=True)

    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            path.write_bytes(content)
        else:
            path.write_text(content, encoding="utf-8")


def check(files: dict[Path, str | bytes]) -> int:
    problems = 0
    for path, content in sorted(files.items()):
        if not path.exists():
            print(f"missing: {path.relative_to(ROOT)}")
            problems += 1
            continue
        current = path.read_bytes()
        wanted = content.encode("utf-8") if isinstance(content, str) else content
        if current != wanted:
            print(f"stale:   {path.relative_to(ROOT)}")
            problems += 1

    # Stale files that the generator no longer emits are drift too.
    expected = set(files)
    for directory in (OUT_AGENTS, OUT_SKILLS, OUT_COMMANDS):
        if not directory.exists():
            continue
        for path in directory.rglob("*"):
            if path.is_file() and path not in expected:
                rel = path.relative_to(ROOT)
                if path.suffix == ".md":
                    print(f"extra:   {rel}")
                    problems += 1

    if problems:
        print(
            f"\n{problems} generated file(s) differ. Run `python3 tools/sync-opencode.py`.",
            file=sys.stderr,
        )
        return 1
    print(f"OpenCode adapter is in sync ({len(files)} files).")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the adapter is stale")
    parser.add_argument("--verbose", action="store_true", help="list generated files")
    args = parser.parse_args()

    files = build()
    if args.check:
        return check(files)

    write_files(files)
    if args.verbose:
        for path in sorted(files):
            print(path.relative_to(ROOT))
    print(f"Generated {len(files)} OpenCode files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
