#Requires -Version 7.0
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$marker = 'Generated by .codex/scripts/sync-adapter.ps1'

function Get-MetadataValue {
    param([string]$Frontmatter, [string]$Key, [string]$Path)

    # Read the top-level scalar fields used here. Claude tool arguments and
    # unrelated fields do not need to be parsed.
    $fields = [regex]::Matches($Frontmatter, "(?m)^$($Key):[ \t]*(?<first>[^\n]*)(?<rest>(?:\n(?:[ \t]+[^\n]*|(?=\n)))*)")
    if ($fields.Count -eq 0) { return '' }
    if ($fields.Count -ne 1) { throw "Duplicate field '$Key' in $Path" }

    $first = $fields[0].Groups['first'].Value.Trim()
    $rest = $fields[0].Groups['rest'].Value
    if ($first -match '^([|>])[+-]?(?:[ \t]+#.*)?$') {
        $style = $Matches[1]
        $lines = $rest.Trim("`n") -split "`n" | ForEach-Object { $_.Trim() }
        if ($style -eq '|') { return ($lines -join "`n").Trim() }
        return (($lines -join ' ') -replace ' {2,}', ' ').Trim()
    }

    $scalar = ($first + ($rest -replace '\n[ \t]*', ' ')).Trim()
    if ($scalar -match '^("(?:[^"\\]|\\.)*")(?:[ \t]+#.*)?$') {
        return (ConvertFrom-Json -InputObject $Matches[1])
    }
    if ($scalar -match "^'(?<value>(?:[^']|'')*)'(?:[ \t]+#.*)?$") {
        return $Matches['value'].Replace("''", "'")
    }
    if ($scalar -match '^["''|>]') { throw "Unsupported scalar for '$Key' in $Path" }
    return ($scalar -replace '[ \t]+#.*$').Trim()
}

function Get-SourceMetadata {
    param([IO.FileInfo]$Source, [string]$ExpectedName, [string[]]$ExtraKeys)

    $content = [IO.File]::ReadAllText($Source.FullName).Replace("`r`n", "`n")
    $header = [regex]::Match($content, '(?s)\A---\n(?<body>.*?)\n---(?:\n|\z)')
    if (-not $header.Success) { throw "Missing frontmatter in $($Source.FullName)" }

    $metadata = @{}
    foreach ($key in @('name', 'description') + $ExtraKeys) {
        $metadata[$key] = Get-MetadataValue $header.Groups['body'].Value $key $Source.FullName
    }
    if ($metadata.name -cne $ExpectedName -or
        $metadata.name -cnotmatch '^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$' -or
        $metadata.name -match '^(?:con|prn|aux|nul|com[0-9]|lpt[0-9])$') {
        throw "Invalid name '$($metadata.name)' for $($Source.FullName)"
    }
    if ([string]::IsNullOrWhiteSpace($metadata.description)) {
        throw "Missing description in $($Source.FullName)"
    }
    return $metadata
}

function Assert-RegularPath {
    param([string]$Path)

    # Generated files stay under this checkout even when local junctions or
    # symbolic links exist.
    $candidate = $Path
    while ($candidate -ne $root) {
        if ([string]::IsNullOrEmpty($candidate)) { throw "Adapter path outside checkout: $Path" }
        $item = Get-Item -LiteralPath $candidate -Force -ErrorAction SilentlyContinue
        if ($null -ne $item -and ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) {
            throw "Adapter path must not be a link: $candidate"
        }
        $candidate = [IO.Path]::GetDirectoryName($candidate)
    }
}

function Test-GeneratedFile {
    param([string]$Content)

    $normalized = $Content.Replace("`r`n", "`n")
    if (($normalized -split "`n", 2)[0] -ceq "# $marker.") { return $true }
    $header = [regex]::Match($normalized, '(?s)\A---\n.*?\n---\n\n(?<marker>[^\n]*)')
    return $header.Groups['marker'].Value -ceq "<!-- $marker. -->"
}

function Write-GeneratedFile {
    param([string]$Path, [string]$Content, [bool]$Replace)

    $directory = [IO.Path]::GetDirectoryName($Path)
    [IO.Directory]::CreateDirectory($directory) | Out-Null
    $tempPath = Join-Path $directory ([IO.Path]::GetRandomFileName())
    try {
        [IO.File]::WriteAllText($tempPath, $Content)
        [IO.File]::Move($tempPath, $Path, $Replace)
    } finally {
        [IO.File]::Delete($tempPath)
    }
}

$expected = [Collections.Generic.Dictionary[string, string]]::new([StringComparer]::OrdinalIgnoreCase)
$sourceSkills = @(Get-ChildItem -LiteralPath (Join-Path $root '.claude/skills') -Directory |
    ForEach-Object { Get-Item -LiteralPath (Join-Path $_.FullName 'SKILL.md') -ErrorAction SilentlyContinue } |
    Sort-Object FullName)
$sourceAgents = @(Get-ChildItem -LiteralPath (Join-Path $root '.claude/agents') -File -Filter '*.md' |
    Sort-Object FullName)
if ($sourceSkills.Count -eq 0 -or $sourceAgents.Count -eq 0) {
    throw 'Missing canonical CCGS skill or agent files.'
}

foreach ($source in $sourceSkills) {
    $metadata = Get-SourceMetadata $source $source.Directory.Name @('disable-model-invocation')
    $name = $metadata.name
    # JSON strings are valid YAML and TOML basic strings for this metadata.
    $description = ConvertTo-Json -InputObject $metadata.description -Compress
    $expected.Add((Join-Path $root ".agents/skills/$name/SKILL.md"), @"
---
name: $name
description: $description
---

<!-- $marker. -->
Read the workflow in .claude/skills/$name/SKILL.md before acting.
Follow its Markdown body using the Codex compatibility mapping in AGENTS.md.
"@)
    if ($metadata.'disable-model-invocation' -eq 'true') {
        $expected.Add((Join-Path $root ".agents/skills/$name/agents/openai.yaml"), @"
# $marker.
policy:
  allow_implicit_invocation: false
"@)
    }
}

foreach ($source in $sourceAgents) {
    $metadata = Get-SourceMetadata $source $source.BaseName @('tools', 'disallowedTools', 'memory', 'skills', 'isolation')
    $name = $metadata.name
    $description = ConvertTo-Json -InputObject $metadata.description -Compress
    $instructions = @(
        "Read the role in .claude/agents/$name.md before acting."
        'Follow its Markdown body using the Codex compatibility mapping in AGENTS.md.'
        'Return decisions and approval requests to the parent for the user to resolve.'
    )
    if ($metadata.memory -eq 'project') {
        $instructions += "Read .claude/agent-memory/$name/MEMORY.md if present and apply .claude/rules/agent-memory.md."
    }
    if ($metadata.isolation -eq 'worktree') {
        $instructions += 'Verify that the parent assigned a separate Git worktree before editing. If it is missing, return the requirement to the parent.'
    }
    if ($metadata.skills) {
        $skills = $metadata.skills.Trim('[', ']')
        if ($skills -cnotmatch '^[a-z0-9-]+(?:,\s*[a-z0-9-]+)*$') {
            throw "Invalid preloaded skill list in $($source.FullName)"
        }
        $instructions += "Read the canonical workflow for each preloaded skill relevant to your assignment ($skills)."
    }
    if (($metadata.tools -split '\s*,\s*') -notcontains 'Bash' -or
        ($metadata.disallowedTools -split '\s*,\s*') -contains 'Bash') {
        $instructions += 'Use dedicated file tools for reads, searches, and approved edits. Limit PowerShell to those file operations when no dedicated tool is available.'
    }
    $expected.Add((Join-Path $root ".codex/agents/$name.toml"), @"
# $marker.
name = "$name"
description = $description
developer_instructions = '''
$($instructions -join "`n")
'''
"@)
}

$skillRoot = Join-Path $root '.agents/skills'
$agentRoot = Join-Path $root '.codex/agents'
Assert-RegularPath $skillRoot
Assert-RegularPath $agentRoot
$changes = [Collections.Generic.List[object]]::new()
foreach ($path in ($expected.Keys | Sort-Object)) {
    Assert-RegularPath $path
    $content = $expected[$path].Replace("`r`n", "`n") + "`n"
    $exists = Test-Path -LiteralPath $path
    if ($exists) {
        $current = [IO.File]::ReadAllText($path).Replace("`r`n", "`n")
        if ($current -ceq $content) { continue }
        if (-not (Test-GeneratedFile $current)) { throw "Handwritten adapter already exists: $path" }
    }
    $changes.Add(@{ Path = $path; Content = $content; Exists = $exists })
}

$existingPaths = @(
    if (Test-Path -LiteralPath $skillRoot) {
        foreach ($folder in (Get-ChildItem -LiteralPath $skillRoot -Directory)) {
            if ($folder.Attributes -band [IO.FileAttributes]::ReparsePoint) { continue }
            Join-Path $folder.FullName 'SKILL.md'
            Join-Path $folder.FullName 'agents/openai.yaml'
        }
    }
    if (Test-Path -LiteralPath $agentRoot) {
        Get-ChildItem -LiteralPath $agentRoot -File -Filter '*.toml' | ForEach-Object FullName
    }
)
foreach ($path in $existingPaths) {
    if ($expected.ContainsKey($path) -or -not (Test-Path -LiteralPath $path -PathType Leaf)) { continue }
    Assert-RegularPath $path
    if (Test-GeneratedFile ([IO.File]::ReadAllText($path))) {
        $changes.Add(@{ Path = $path; Content = $null; Exists = $true })
    }
}

foreach ($change in $changes) {
    $relativePath = [IO.Path]::GetRelativePath($root, $change.Path)
    $action = if ($null -eq $change.Content) { 'Stale' } elseif ($change.Exists) { 'Changed' } else { 'Missing' }
    Write-Host "$action $relativePath"
    if ($Check) { continue }
    if ($null -eq $change.Content) {
        Remove-Item -LiteralPath $change.Path
    } else {
        Write-GeneratedFile $change.Path $change.Content $change.Exists
    }
}
if ($Check -and $changes.Count -gt 0) {
    throw 'Codex adapter drift detected. Run pwsh -NoProfile -File .codex/scripts/sync-adapter.ps1.'
}

Write-Host "Codex adapter synchronized ($($sourceSkills.Count) skills, $($sourceAgents.Count) agents, $($changes.Count) file changes)."
